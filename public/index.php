<?php

error_reporting(E_ALL);
ini_set('display_errors', '1');
ini_set('display_startup_errors', '1');

use Dotenv\Dotenv;
use App\Exceptions\Handler;


/*
|--------------------------------------------------------------------------
| Composer Autoload
|--------------------------------------------------------------------------
*/

require __DIR__ . '/../vendor/autoload.php';


/*
|--------------------------------------------------------------------------
| Base Path
|--------------------------------------------------------------------------
*/

define(
    'BASE_PATH',
    dirname(__DIR__)
);


/*
|--------------------------------------------------------------------------
| Load Environment Variable
|--------------------------------------------------------------------------
*/

$dotenv = Dotenv::createImmutable(
    BASE_PATH
);

$dotenv->load();


/*
|--------------------------------------------------------------------------
| Load Configuration
|--------------------------------------------------------------------------
*/

$appConfig = require BASE_PATH . '/app/Config/app.php';

$dbConfig = require BASE_PATH . '/app/Config/database.php';

$mailConfig = require BASE_PATH . '/app/Config/mail.php';

require BASE_PATH . '/app/Config/constants.php';



/*
|--------------------------------------------------------------------------
| Application Timezone
|--------------------------------------------------------------------------
*/

date_default_timezone_set(
    $appConfig['timezone']
);



/*
|--------------------------------------------------------------------------
| Session Start
|--------------------------------------------------------------------------
*/

session_name(
    $appConfig['session']['name']
);

session_start();



/*
|--------------------------------------------------------------------------
| Register Exception Handler
|--------------------------------------------------------------------------
*/

Handler::register();



/*
|--------------------------------------------------------------------------
| Load Routes
|--------------------------------------------------------------------------
*/

$router = require BASE_PATH . '/routes/web.php';



/*
|--------------------------------------------------------------------------
| Dispatch Request
|--------------------------------------------------------------------------
*/

$router->dispatch();